export function t(message: string, values?: Record<string, string | number>): string {
  const limit = !values && /^(Minimum|Maximum): (.+)\.$/.exec(message);
  if (limit) return t(limit[1] + ': {value}.', { value: limit[2] });
  const translated = activeLocale === 'es' && Object.hasOwn(messages, message) ? spanish[message as MessageKey] : message;
  return values ? translated.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match)) : translated;
}
