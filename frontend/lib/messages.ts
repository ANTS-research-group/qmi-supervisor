export type MessageKey = keyof typeof messages;
export type Locale = 'en' | 'es';
export const english: Record<MessageKey, string> = Object.fromEntries(Object.keys(messages).map(key => [key, key])) as Record<MessageKey, string>;
export const spanish: Record<MessageKey, string> = { ...messages };
let activeLocale: Locale = 'en';
export const getLocale = () => activeLocale;
export const setLocale = (locale: Locale) => { activeLocale = locale; };
export const intlLocale = () => activeLocale === 'es' ? 'es-ES' : 'en-GB';
export function t(message: string, values?: Record<string, string | number>): string {
  const limit = !values && /^(Minimum|Maximum): (.+)\.$/.exec(message);
  if (limit) return t(limit[1] + ': {value}.', { value: limit[2] });
  const translated = activeLocale === 'es' && Object.hasOwn(messages, message) ? spanish[message as MessageKey] : message;
  return values ? translated.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match)) : translated;
}
